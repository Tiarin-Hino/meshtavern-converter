/**
 * An icon of the package as inline SVG on one line: decorative (`aria-hidden`), not focusable,
 * in currentColor, with the class `icon` that components.css sizes to the text around it. The
 * same rewrite as the application's `iconMarkup`, without the space it leaves before a `>`.
 */
export function iconMarkup(svg) {
  return svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(
      /^\s*<svg\s+class="lucide lucide-[\w-]+"/,
      '<svg class="icon" aria-hidden="true" focusable="false"',
    )
    .replace(/\s*\n\s*/g, ' ')
    .replace(/\s+(\/?)>/g, '$1>')
    .replace(/> </g, '><')
    .trim();
}

/** The package's SVG file of an icon, from `root` (the repo by default). */
export function readIcon(name, root = new URL('../../', import.meta.url)) {
  return readFileSync(new URL(`node_modules/lucide-static/icons/${name}.svg`, root), 'utf8');
}

/** The source of the module at `path` (a key of ICON_SETS), formatted as Prettier formats it. */
export async function iconModule(path, read = readIcon) {
  const names = ICON_SETS[path];
  if (names === undefined) throw new Error(`no icon set for ${path}`);
  const entries = names.map((name) => `  '${name}': ${JSON.stringify(iconMarkup(read(name)))},`);
  const source = `// Generated by scripts/make-icons.mjs (npm run icons) from lucide-static ${LUCIDE_VERSION}: do not edit by
// hand. Lucide is ISC-licensed; the licence and Feather's MIT notice are in
// public/theme/LICENSE-Lucide.txt. Each icon is inline SVG in currentColor with the class \`icon\`,
// decorative: the control around it carries the accessible name.

export const ICONS = {
${entries.join('\n')}
} as const satisfies Record<string, string>;

export type IconName = keyof typeof ICONS;
`;
  const config = await resolveConfig(new URL(`../../${path}`, import.meta.url));
  return format(source, { ...config, filepath: path });
}
